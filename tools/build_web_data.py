"""
Regenerate docs/data.js from the Python presets.

Run this after editing caption_styles.py or facecam_layouts.py:

    python tools/build_web_data.py
"""

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from caption_styles import (  # noqa: E402
    ANIMATIONS,
    CAPTION_EFFECTS,
    CAPTION_POSITIONS,
    CAPTION_STYLES,
    DEFAULT_ANIMATION,
    DEFAULT_EFFECT,
    DEFAULT_STYLE,
)
from clipper_config import DEFAULT_CONFIG, RATIOS  # noqa: E402
from facecam_layouts import (  # noqa: E402
    FACECAM_MODES,
    OVERLAY_POSITIONS,
    SOURCE_POSITIONS,
)


def main():
    data = {
        "styles": CAPTION_STYLES,
        "animations": ANIMATIONS,
        "effects": CAPTION_EFFECTS,
        "positions": CAPTION_POSITIONS,
        "facecamModes": FACECAM_MODES,
        "sourcePositions": list(SOURCE_POSITIONS),
        "overlayPositions": list(OVERLAY_POSITIONS),
        "ratios": list(RATIOS),
        "defaults": DEFAULT_CONFIG,
        "defaultStyle": DEFAULT_STYLE,
        "defaultAnimation": DEFAULT_ANIMATION,
        "defaultEffect": DEFAULT_EFFECT,
    }

    out_path = os.path.join(ROOT, "docs", "data.js")
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as handle:
        handle.write("/* Auto-generated by tools/build_web_data.py - do not edit manually */\n")
        handle.write("window.CLIPPER_DATA = ")
        json.dump(data, handle, indent=2, ensure_ascii=False)
        handle.write(";\n")
    print(f"Wrote {out_path}")


if __name__ == "__main__":
    main()
